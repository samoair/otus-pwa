<template>
  <!--
    router-view — точка монтирования текущего маршрута.
    Vue Router подставляет сюда компонент, соответствующий текущему URL.
    Например, '/' → IndexPage.vue, '/about' → AboutPage.vue.
  -->
  <router-view />
</template>

<script setup lang="ts">
// App.vue — корневой компонент всего приложения.
//
// <script setup lang="ts"> — это «синтаксический сахар» Composition API.
// Во что он компилируется (упрощённо):
//
//   export default {
//     setup() {
//       // всё, что написано внутри <script setup>,
//       // попадает внутрь функции setup()
//       return { /* всё, что используется в шаблоне */ }
//     }
//   }
//
// Преимущества перед обычным setup():
//   - не нужно писать return — компилятор сам определяет,
//     какие переменные используются в шаблоне
//   - не нужно регистрировать компоненты через components: {}
//   - оптимизация производительности — код компилируется
//     в более эффективный рантайм
//   - TypeScript работает «из коробки» — типы props, emit и т.д.
</script>
